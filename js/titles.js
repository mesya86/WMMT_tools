document.addEventListener('DOMContentLoaded', () => {
  const selector = document.getElementById('monthSelector');
  const table = document.getElementById('titleTable');
  const tableBody = document.getElementById('titleTableBody');

  // 1. データを日付ごとに整理（ここは前回と同じ）
  const calendar = {};
  const mergeData = (dataArray, label) => {
    dataArray.forEach(row => {
      const date = row[0];
      const month = date.split('/')[0];
      if (!calendar[month]) calendar[month] = {};
      if (!calendar[month][date]) calendar[month][date] = { even: [], odd: [] };
      if (label === "偶数") { calendar[month][date].even = row.slice(1); }
      else { calendar[month][date].odd = row.slice(1); }
    });
  };

  mergeData(titlesEven, "偶数");
  mergeData(titlesOdd, "奇数");

  // 2. セレクトボックスが変更された時の処理
  selector.addEventListener('change', (e) => {
    const selectedMonth = e.target.value;

    if (!selectedMonth) {
      table.style.display = 'none';
      return;
    }

    // 中身を一度空にする
    tableBody.innerHTML = '';

    // 選択された月のデータを流し込む
    const monthData = calendar[selectedMonth];
    if (monthData) {
      Object.keys(monthData).sort().forEach(date => {
        const day = monthData[date];
        const tr = document.createElement('tr');
        tr.innerHTML = `
          <td style="font-size: 0.8rem; vertical-align: middle;">${date}</td>
          <td style="text-align: left; font-size: 0.75rem; white-space: normal; line-height: 1.4;">
            ${day.even.join('<br>')}
          </td>
          <td style="text-align: left; font-size: 0.75rem; white-space: normal; line-height: 1.4;">
            ${day.odd.join('<br>')}
          </td>
        `;
        tableBody.appendChild(tr);
      });

      // テーブルを表示
      table.style.display = 'table';
      
      // スッと表示されるアニメーション（お好みで）
      table.style.opacity = '0';
      setTimeout(() => {
        table.style.transition = 'opacity 0.3s';
        table.style.opacity = '1';
      }, 10);
    }
  });
});